/**
 * モニュメントの 16×16 ドット絵（2×2 タイル分）。
 *
 * 実在の建造物の「形の特徴」をドット絵に起こしたもので、
 * 写真・図面・第三者の素材は使用していない。すべてこのファイルのコードで描いている。
 */
object MonumentSprites {
    const val SIZE = 16

    private fun sprite(vararg rows: String): ByteArray {
        require(rows.size == SIZE) { "monument sprite must have $SIZE rows, got ${rows.size}" }
        val out = ByteArray(SIZE * SIZE)
        rows.forEachIndexed { y, row ->
            require(row.length == SIZE) { "row $y must be $SIZE wide, got ${row.length}" }
            row.forEachIndexed { x, ch ->
                out[y * SIZE + x] = when (ch) {
                    '.' -> 0
                    '-' -> 1
                    '+' -> 2
                    '#' -> 3
                    else -> throw IllegalArgumentException("bad pixel '$ch'")
                }
            }
        }
        return out
    }

