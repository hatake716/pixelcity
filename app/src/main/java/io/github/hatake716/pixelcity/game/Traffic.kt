package io.github.hatake716.pixelcity.game

import kotlin.math.exp
import kotlin.math.pow

/**
 * 交通量の計算。交通工学で使われている式をそのまま使う。
 *
 * 思いつきの数式ではなく、実際の都市計画で使われているものを採る。
 * そうすると「道を1本足したら、どこが楽になるか」が現実と同じ理屈で動き、
 * 遊ぶ人の予想と噛み合う。
 *
 * ## 使っている式
 *
 * **1. BPR式**（Bureau of Public Roads, 1964『Traffic Assignment Manual』）
 *
 * ```
 * t = t0 * (1 + α * (v / c)^β)      α = 0.15, β = 4
 * ```
 *
 * 混んだ道を通る時間。v/c が 1.0（容量ちょうど）で 1.15倍、
 * 1.5倍で 1.76倍、2.0倍で 3.4倍。容量を超えても無限にならないので、
 * 詰まった道も計算が破綻しない。α=0.15・β=4 は世界共通の既定値。
 *
 * **2. 重力モデル**（trip distribution）
 *
 * ```
 * T_ij ∝ P_i * A_j * d_ij^(-β)      β = 2.0
 * ```
 *
 * どこからどこへ人が動くか。住宅（P）から職場（A）へ、
 * 距離の2乗に反比例して流れる。ニュートンの万有引力と同じ形。
 *
 * **3. Greenshields のモデル**（Greenshields, 1935）
 *
 * ```
 * v = vf * (1 - k / kj)            速度は密度に反比例して落ちる
 * q_max = vf * kj / 4              容量は「自由速度の半分」で出る
 * ```
 *
 * 車がどれだけの速さで走るか。混むほど遅くなる。
 * 車のアニメーションの速さは、この式から出す。
 *
 * **4. サービス水準（LOS）** — v/c から A〜F の6段階。
 * 米国 Highway Capacity Manual の計画段階の目安に合わせる。
 *
 * **5. Wardrop の第一原則**（Wardrop, 1952）
 *
 * 「使われている経路の所要時間はすべて等しく、
 * 使われていない経路より短い」＝ 利用者均衡。
 * みなが自分にとって最短の道を選ぶ結果、こうなる。
 * ここでは反復回数を抑えた MSA（逐次平均法）で近づける。
 */
object Traffic {

    // ------------------------------------------------------------------
    // BPR式
    // ------------------------------------------------------------------

    /** BPR式の係数。1964年の原典の値で、いまも既定値として使われている。 */
    const val BPR_ALPHA = 0.15
    const val BPR_BETA = 4.0

    /**
     * 混雑したときの所要時間の倍率。
     *
     * [vc] は 交通量 ÷ 容量。1.0 で容量ちょうど。
     * 戻り値は「すいているときの何倍か」。
     */
    fun delayFactor(vc: Float): Float =
        (1.0 + BPR_ALPHA * vc.toDouble().coerceAtLeast(0.0).pow(BPR_BETA)).toFloat()

    // ------------------------------------------------------------------
    // サービス水準（LOS）
    // ------------------------------------------------------------------

    /**
     * 道の混み具合。米国 Highway Capacity Manual の6段階。
     *
     * [label] は画面に出す名前、[vcMax] はその等級の上限。
     */
    enum class Los(val grade: String, val label: String, val vcMax: Float) {
        A("A", "すいている", 0.60f),
        B("B", "ながれている", 0.70f),
        C("C", "ふつう", 0.80f),
        D("D", "つまりぎみ", 0.90f),
        E("E", "げんかい", 1.00f),
        F("F", "わたりあい", Float.MAX_VALUE),
        ;

        /** 渋滞と呼ぶ段階か。D 以上で、目に見えて流れが悪くなる。 */
        val isCongested: Boolean get() = ordinal >= D.ordinal
    }

    /** [vc]（交通量÷容量）から、サービス水準を求める。 */
    fun losOf(vc: Float): Los = Los.entries.first { vc <= it.vcMax }

    // ------------------------------------------------------------------
    // Greenshields のモデル
    // ------------------------------------------------------------------

    /**
     * 混み具合に応じた走行速度の割合（自由速度の何倍か）。
     *
     * Greenshields は 速度 = 自由速度 × (1 - 密度/詰まり密度)。
     * 密度は直接持っていないので、v/c から逆算する。
     *
     * 流れは q = v × k で、容量のときに v = vf/2、k = kj/2 になる。
     * そこから、v/c = x のときの速度は
     *
     * ```
     * v/vf = (1 + sqrt(1 - x)) / 2        （x <= 1、すいている側の枝）
     * ```
     *
     * 容量を超えたら、渋滞の枝に入って急に遅くなる。
     * 実際の道路も、容量を超えると流れが崩れて止まりだす。
     */
    fun speedFactor(vc: Float): Float = when {
        vc <= 0f -> 1f
        vc < 1f -> ((1f + Math.sqrt((1f - vc).toDouble()).toFloat()) / 2f)
        // 容量を超えた側。0.5 から下へ、ゆっくり止まっていく。
        else -> (0.5f / (1f + (vc - 1f) * 2.2f)).coerceAtLeast(0.06f)
    }

    // ------------------------------------------------------------------
    // 重力モデル
    // ------------------------------------------------------------------

    /** 重力モデルの距離減衰。2.0 は教科書どおりの値。 */
    const val GRAVITY_BETA = 2.0f

    /**
     * 距離 [d] タイル離れた行き先の、引きつけやすさ。
     *
     * 近いほど強い。0 で割らないよう、最短でも 1 とみなす。
     */
    fun friction(d: Float): Float = d.coerceAtLeast(1f).pow(-GRAVITY_BETA)

    // ------------------------------------------------------------------
    // 1時間あたりの容量
    // ------------------------------------------------------------------

    /**
     * 道の種類ごとの、1時間に通せる台数。
     *
     * Highway Capacity Manual の目安に合わせてある。
     *  - 生活道路: 約600（信号と停止で流れが切れる）
     *  - 大通り: 飽和交通流率 1900 × 青信号の割合 0.5 ≒ 950 を2車線で 1900
     *  - 高速道路: 2000〜2200 を2車線で 4000 前後
     *
     * よくある誤りは、飽和交通流率（青のあいだの流量）を
     * そのまま1時間の容量として使ってしまうこと。
     * 信号のある道は、青の割合ぶんだけ減る。
     */
    fun capacityPerHour(kind: TileKind): Int = when (kind) {
        TileKind.ROAD -> 600
        TileKind.AVENUE -> 1_900
        TileKind.HIGHWAY -> 4_000
        TileKind.RAIL -> 3_000
        TileKind.SUBWAY -> 6_000
        else -> 0
    }

    /**
     * 自由に流れているときの速さ（タイル/秒、画面上の見た目）。
     *
     * 実際の速度をそのまま使うと、遊ぶには速すぎたり遅すぎたりする。
     * 種類ごとの「差」が伝わる範囲に収めてある。
     */
    fun freeFlowSpeed(kind: TileKind): Float = when (kind) {
        TileKind.ROAD -> 0.55f
        TileKind.AVENUE -> 0.85f
        TileKind.HIGHWAY -> 1.5f
        else -> 0.6f
    }
}
